"""Validate downloaded CIDRs or the generated snippet; no network or third-party deps."""
import argparse
import ipaddress
from pathlib import Path


def validate(tokens, version):
    if not tokens or len(tokens) > 100:
        raise ValueError(f"IPv{version}: empty or unexpectedly large range list")
    networks = []
    for token in tokens:
        if "/" not in token:
            raise ValueError(f"Not a CIDR: {token}")
        network = ipaddress.ip_network(token, strict=True)
        if network.version != version or not network.is_global or network.prefixlen < (8 if version == 4 else 16):
            raise ValueError(f"Unexpected IPv{version} network: {token}")
        if any(network.overlaps(other) for other in networks):
            raise ValueError(f"Duplicate/overlapping CIDR: {token}")
        networks.append(network)
    return [str(network) for network in networks]


def read_snippet(path):
    lines = [line.strip() for line in Path(path).read_text().splitlines()
             if line.strip() and not line.lstrip().startswith("#")]
    if len(lines) != 1 or not lines[0].startswith("trusted_proxies static "):
        raise ValueError("Expected one trusted_proxies static directive")
    tokens = lines[0].split()[2:]
    return (validate([t for t in tokens if ":" not in t], 4),
            validate([t for t in tokens if ":" in t], 6))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    generate = commands.add_parser("generate")
    generate.add_argument("ipv4")
    generate.add_argument("ipv6")
    dump = commands.add_parser("dump")
    dump.add_argument("snippet")
    args = parser.parse_args()
    if args.command == "generate":
        v4 = validate(Path(args.ipv4).read_text().split(), 4)
        v6 = validate(Path(args.ipv6).read_text().split(), 6)
        print("# Generated by scripts/update-cloudflare-ips.sh from Cloudflare ips-v4 and ips-v6.")
        print("trusted_proxies static " + " ".join(v4 + v6))
    else:
        for version, networks in zip((4, 6), read_snippet(args.snippet)):
            for network in networks:
                print(version, network)


if __name__ == "__main__":
    main()
